    func testSortedMarkerDrawAndRedrawReconcileWithTheCanonicalHand() throws {
        var game = try fixture()
        let digit = try XCTUnwrap(game.puzzle?.hand[2])
        let square = try XCTUnwrap(game.puzzle?.board.blanks.first {
            game.puzzle?.board.correctDigit(at: $0) == digit
        })
        game.qaSetMarker("mk_sapphire", at: square)
        let model = GameModel(resuming: game, savesProgress: false)
        model.arrangeHand(.descending)
        model.tapHandCard(model.handCards[2].id)
        model.tapSquare(square)
        XCTAssertEqual(model.lastOutcome?.numbersDrawn, 1)
        XCTAssertEqual(model.displayedHandCards.map(\.digit), model.hand.sorted(by: >))
        model.qaSetBuff(Buffs.redraw)
        let old = model.handCards.map(\.id)
        XCTAssertTrue(model.useBuff(at: 0))
        XCTAssertTrue(Set(old).isDisjoint(with: model.handPresentationOrder))
        XCTAssertEqual(model.numberReturns.last?.handCardIDs, old)
        XCTAssertEqual(model.displayedHandCards.map(\.digit), model.hand.sorted(by: >))
        assertCompletePermutation(model)
    }

    func testFinalCardAutomaticTurnRefillReconcilesOnceWithSortedPresentation() throws {
        var run = try fixture().run
        var puzzle = try XCTUnwrap(run.puzzle)
        for digit in puzzle.hand.dropFirst() { puzzle.pool.put(digit) }
        puzzle.hand = Array(puzzle.hand.prefix(1))
        puzzle.target = 100_000
        run.puzzle = puzzle
        let model = GameModel(resuming: Game(run: run), savesProgress: false)
        model.arrangeHand(.ascending)
        let selected = try XCTUnwrap(model.handCards.first)
        let turn = puzzle.turnNumber
        let square = try blank(in: model, matching: selected.digit)
        model.tapHandCard(selected.id)
        model.tapSquare(square)
        XCTAssertEqual(model.puzzle?.turnNumber, turn + 1)
        XCTAssertFalse(model.handPresentationOrder.contains(selected.id))
        XCTAssertEqual(model.displayedHandCards.map(\.digit), model.hand.sorted())
        let before = model.game
        model.tapHandCard(selected.id) // An old tile's delayed tap is ignored.
        XCTAssertNil(model.selectedHandIndex)
        XCTAssertNil(RunStore.conflict(local: before, remote: model.game))
        assertCompletePermutation(model)
    }

    func testPresentationResumeRestoresRandomPermutationAndRejectsStaleOrDifferentRun() throws {
        let model = try makeModel()
        model.arrangeHand(.random)
        let saved = try XCTUnwrap(model.handPresentation)
        let encoded = try JSONEncoder().encode(saved)
        let restored = try JSONDecoder().decode(GameModel.HandPresentation.self, from: encoded)
        let resumed = GameModel(resuming: try Game(decoding: model.game.encoded()), savesProgress: false)
        let gameBefore = resumed.game
        XCTAssertTrue(resumed.restoreHandPresentation(restored))
        XCTAssertEqual(resumed.handCards, model.handCards)
        XCTAssertEqual(resumed.handPresentationOrder, model.handPresentationOrder)
        XCTAssertEqual(resumed.handArrangement, .random)
        XCTAssertNil(RunStore.conflict(local: gameBefore, remote: resumed.game))
        resumed.endTurn()
        let newOrder = resumed.handPresentationOrder
        XCTAssertFalse(resumed.restoreHandPresentation(restored))
        XCTAssertEqual(resumed.handPresentationOrder, newOrder)
        var other = Game(seed: "different-arrangement-run")
        try other.startPuzzle()
        XCTAssertFalse(GameModel(resuming: other, savesProgress: false).restoreHandPresentation(restored))
    }

    private func makeModel() throws -> GameModel {
        GameModel(resuming: try fixture(), savesProgress: false)
    }

    private func fixture() throws -> Game {
        var game = Game(seed: "hand-arrangement", book: .noPressure)
        try game.startPuzzle()
        var run = game.run
        var puzzle = try XCTUnwrap(run.puzzle)
        for digit in puzzle.hand { puzzle.pool.put(digit) }
        let duplicate = try XCTUnwrap(Digit.all.reversed().first { puzzle.pool[$0] >= 2 })
        let others = Digit.all.filter { $0 != duplicate && puzzle.pool[$0] > 0 }
        XCTAssertGreaterThanOrEqual(others.count, 2)
        puzzle.hand = []
        puzzle.handSize = 4
        puzzle.cluesRemaining = 2
        for digit in [duplicate, others[0], duplicate, others[1]] {
            XCTAssertTrue(puzzle.pool.take(digit))
            puzzle.hand.append(digit)
        }
        run.puzzle = puzzle
        return Game(run: run)
    }

    private func blank(in model: GameModel, matching digit: Digit) throws -> Square {
        try XCTUnwrap(model.puzzle?.board.blanks.first { model.puzzle?.board.correctDigit(at: $0) == digit })
    }

    private func streamStates(_ game: Game) -> [UInt32] {
        [game.run.streams.board.state, game.run.streams.pool.state,
         game.run.streams.shop.state, game.run.streams.boss.state]
    }

    private func assertCompletePermutation(_ model: GameModel,
                                           file: StaticString = #filePath, line: UInt = #line) {
        XCTAssertEqual(model.handCards.map(\.digit), model.hand, file: file, line: line)
        XCTAssertEqual(Set(model.handPresentationOrder), Set(model.handCards.map(\.id)), file: file, line: line)
        XCTAssertEqual(model.handPresentationOrder.count, model.handCards.count, file: file, line: line)
        XCTAssertEqual(model.displayedHandCards.count, model.handCards.count, file: file, line: line)
    }
